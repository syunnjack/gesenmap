  <h1>公式のルール</h1>
  <p class="text-muted">
    ゲームセンターの決まりは、風俗営業等の規制及び業務の適正化等に関する法律（風営法）と、
    警察庁が出している解釈運用基準に書かれています。
    ここでは条文と通達にあたって、実際に書かれていることだけをまとめました。
  </p>

  <section class="mb-4">
    <h2 class="h5">ゲームセンターは、法律ではどう扱われていますか</h2>
    <p>
      風営法第2条第1項第5号にあたる営業です。条文では「スロットマシン、テレビゲーム機その他の遊技設備で
      本来の用途以外の用途として射幸心をそそるおそれのあるものを備える店舗において、当該遊技設備により
      客に遊技をさせる営業」と書かれています。業界では「5号営業」と呼ばれます。
      風俗営業なので、営業には都道府県公安委員会の許可が必要です。
    </p>
  </section>

  <section class="mb-4">
    <h2 class="h5">景品の値段に上限はありますか</h2>
    <p>
      法律の条文には金額が書かれていません。風営法第23条第2項は、ゲームセンターを営む者は
      「遊技の結果に応じて賞品を提供してはならない」とだけ定めています。
    </p>
    <p>
      金額が出てくるのは、警察庁の解釈運用基準（通達）のほうです。そこには、クレーンで釣り上げるなどした
      物品で<strong>小売価格がおおむね1,000円以下</strong>のものを提供する場合は、第23条第2項の
      「遊技の結果に応じて賞品を提供」することには当たらないものとして取り扱う、と書かれています。
      実質的にここが景品の上限になっています。
    </p>
    <p>
      よく「ゲームセンターの景品は800円まで」と説明されますが、<strong>800円という数字はぱちんこ屋
      （法第2条第1項第4号の営業）についての決まり</strong>から来ています。クレーンゲームの景品の話ではありません。
    </p>
  </section>

  <section class="mb-4">
    <h2 class="h5">18歳未満は何時まで遊べますか</h2>
    <p>
      風営法第22条第1項第5号で、ゲームセンターの営業所には、<strong>午後10時から翌日の午前6時まで</strong>の間、
      18歳未満の人を客として立ち入らせてはならないと定められています。これは全国共通です。
    </p>
    <p>
      そのうえで同条第2項が、都道府県は条例で、午前6時のあとから午後10時前までの時間についても、
      18歳未満の立入りを禁止したり、保護者の同伴を求めたりできると定めています。
      「16時まで」「18時まで」といった時間の違いは、ここから来ています。
    </p>
    <p>
      つまり、住んでいる地域によって遊べる時間が違います。実際の時刻は、店頭の掲示か、
      お住まいの都道府県警察の案内でご確認ください。
      当サイトでは都道府県ごとの時刻を書いていません。条例は改正されるため、
      書き写すと古いまま残ってしまいます。
    </p>
  </section>

  <section class="mb-4">
    <h2 class="h5">お店は何時まで営業できますか</h2>
    <p>
      風営法第13条第1項で、風俗営業者は深夜（午前0時から午前6時まで）に営業してはならないと
      定められています。ゲームセンターもこれに含まれます。
      ただし同項のただし書きで、都道府県の条例に特別の定めがある場合は、条例で定める地域に限り、
      午前0時以後も条例で定める時まで営業できるとされています。深夜も開いている店があるのはこのためです。
    </p>
  </section>

  <section class="mb-4">
    <h2 class="h5">メダルゲームのメダルを持ち帰れないのはなぜですか</h2>
    <p>
      法律で禁じられているためです。風営法第23条第3項が、同条第1項第3号をゲームセンターにも準用しています。
      第3号は「遊技の用に供する玉、メダルその他これらに類する物を客に営業所外に持ち出させること」の禁止です。
    </p>
    <p>
      同じく準用される第4号で、メダルを客のために保管したことを表示する書面を発行することも禁じられています。
      店にメダルを預けたときに預り証が出ないのは、このためです。
      警察庁の解釈運用基準では、獲得した得点や数量を電磁的な方法で記録した媒体を発行・交付することも
      この第4号に違反するとされており、カードに記録して持ち帰る形も認められていません。
    </p>
  </section>

  <section class="mb-4">
    <h2 class="h5">やってはいけないことは何ですか</h2>
    <p>
      台を叩く、揺らす、こじ開ける、取り出し口から手や体を入れるといった行為は、どの店でも禁止されています。
      景品や機械が壊れるだけでなく、けがや事故につながります。店によっては退店を求められ、
      器物損壊などに問われることもあります。
    </p>
    <p>
      偶然の勝敗に関して金品を賭ける行為は、賭博罪に当たる可能性があります。警察庁も遊技場営業について、
      名目を問わず偶然の勝敗に関して財物を賭ける行為は賭博罪に該当する可能性がある、と案内しています。
    </p>
    <p>
      景品が取れない位置に入り込んでしまったときは、自分で何とかしようとせず店員さんに声をかけてください。
      位置を直してもらえることがあります。
    </p>
  </section>

